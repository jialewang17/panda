def normalize_query(question: str) -> str:
    """将口语/不规范问句改写为更易检索的标准表述。"""
    text = str(question or "").strip()
    if not text:
        return ""
    # 轻度清洗：统一空白与问号
    text = text.replace("？", "?").replace("　", " ")
    text = " ".join(text.split())
    for src, dst in _COLLOQUIAL_REPLACEMENTS:
        if src in text:
            text = text.replace(src, dst)
    return text.strip()


def list_colloquial_aliases() -> List[Dict[str, str]]:
    """调试用：列出全部口语 → 标准映射。"""
    return [{"colloquial": src, "canonical": dst} for src, dst in _COLLOQUIAL_REPLACEMENTS]
